#!/usr/bin/env python3
"""C2 Home theme bridge.

Serves the current Omarchy theme and a TV-sized wallpaper over the LAN, and
pushes changes over Server-Sent Events. Read-only: it never writes Omarchy
state or accepts commands.

The endpoint is intentionally tiny: /api/theme, /api/wallpaper and /events.
Every request requires the token generated by install.sh. The TV keeps one SSE
connection while Home is visible, so idle load is one idle socket.
"""
from __future__ import annotations

import argparse
import hashlib
import hmac
import io
import json
import os
import queue
import re
import select
import shutil
import signal
import stat
import subprocess
import sys
import threading
import time
import tomllib
import urllib.parse
from dataclasses import dataclass, replace
from http.server import BaseHTTPRequestHandler, ThreadingHTTPServer
from pathlib import Path

from PIL import Image, ImageOps

MAX_THEME_NAME = 4096
MAX_COLORS = 65536
MAX_IMAGE = 20_000_000
DEFAULT_PALETTE = {
    "accent": "#89b4fa",
    "foreground": "#cdd6f4",
    "background": "#1e1e2e",
}
HEX = re.compile(r"^#[0-9a-fA-F]{6}$")


def read_regular(path: Path, limit: int) -> tuple[bytes, tuple[int, int, int, int, int]]:
    """Read a bounded regular file and verify it did not change mid-read."""
    fd = os.open(path, os.O_RDONLY | os.O_NONBLOCK)
    with os.fdopen(fd, "rb") as stream:
        before = os.fstat(stream.fileno())
        if not stat.S_ISREG(before.st_mode) or before.st_size > limit:
            raise ValueError("not a size-limited regular file")
        body = stream.read(limit + 1)
        after = os.fstat(stream.fileno())
        if len(body) > limit or identity(before) != identity(after):
            raise ValueError("file changed while reading")
        return body, identity(before)


def identity(metadata: os.stat_result) -> tuple[int, int, int, int, int]:
    return (metadata.st_dev, metadata.st_ino, metadata.st_size,
            metadata.st_mtime_ns, metadata.st_ctime_ns)


def image_mime(data: bytes) -> str:
    if data.startswith(b"\xff\xd8\xff"):
        return "image/jpeg"
    if data.startswith(b"\x89PNG\r\n\x1a\n"):
        return "image/png"
    if data.startswith(b"RIFF") and data[8:12] == b"WEBP":
        return "image/webp"
    raise ValueError("unsupported wallpaper signature")


def clean_color(value, default: str) -> str:
    return value.lower() if isinstance(value, str) and HEX.fullmatch(value) else default


def luminance(hex_color: str) -> float:
    rgb = [int(hex_color[i:i + 2], 16) / 255 for i in (1, 3, 5)]
    linear = [c / 12.92 if c <= 0.04045 else ((c + 0.055) / 1.055) ** 2.4 for c in rgb]
    return 0.2126 * linear[0] + 0.7152 * linear[1] + 0.0722 * linear[2]


@dataclass(frozen=True)
class Snapshot:
    theme: str
    accent: str
    foreground: str
    background: str
    mode: str
    theme_version: str
    wallpaper_version: str
    wallpaper_path: Path
    wallpaper_mime: str
    stale: bool = False

    def payload(self) -> dict:
        return {
            "theme": self.theme,
            "accent": self.accent,
            "foreground": self.foreground,
            "background": self.background,
            "mode": self.mode,
            "version": self.theme_version,
            "wallpaperVersion": self.wallpaper_version,
            "wallpaper": "/api/wallpaper?v=" + self.wallpaper_version,
            "wallpaperName": self.wallpaper_path.name,
            "stale": self.stale,
        }


def read_snapshot(state_dir: Path) -> Snapshot:
    state_dir = Path(state_dir)
    name_bytes, _ = read_regular(state_dir / "theme.name", MAX_THEME_NAME)
    colors_bytes, _ = read_regular(state_dir / "theme" / "colors.toml", MAX_COLORS)
    theme = name_bytes.decode("utf-8").strip()
    if not theme:
        raise ValueError("empty theme name")
    palette = tomllib.loads(colors_bytes.decode("utf-8"))
    accent = clean_color(palette.get("accent"), DEFAULT_PALETTE["accent"])
    foreground = clean_color(palette.get("foreground"), DEFAULT_PALETTE["foreground"])
    background = clean_color(palette.get("background"), DEFAULT_PALETTE["background"])
    mode = palette.get("mode")
    if mode not in ("dark", "light"):
        mode = "light" if luminance(background) > 0.5 else "dark"

    link = state_dir / "background"
    image_path = link.resolve(strict=True)
    metadata = image_path.stat()
    if not image_path.is_file() or metadata.st_size > MAX_IMAGE:
        raise ValueError("wallpaper is not a bounded regular file")
    with image_path.open("rb") as stream:
        header = stream.read(16)
    mime = image_mime(header)

    wallpaper_version = hashlib.sha256(
        (str(image_path) + "\0" + str(metadata.st_dev) + "\0" + str(metadata.st_ino)
         + "\0" + str(metadata.st_size) + "\0" + str(metadata.st_mtime_ns)
         + "\0" + str(metadata.st_ctime_ns)).encode()
    ).hexdigest()[:32]
    theme_version = hashlib.sha256(
        (theme + "\0" + accent + "\0" + foreground + "\0" + background + "\0"
         + mode + "\0" + wallpaper_version).encode() + colors_bytes
    ).hexdigest()[:32]
    return Snapshot(theme, accent, foreground, background, mode,
                    theme_version, wallpaper_version, image_path, mime)


class ThemeState:
    def __init__(self, state_dir: Path):
        self.state_dir = Path(state_dir)
        self.lock = threading.RLock()
        self.snapshot: Snapshot | None = None
        self.generation = 0

    def current(self) -> Snapshot | None:
        with self.lock:
            return self.snapshot

    def refresh(self, retries: int = 3) -> bool:
        """Read a complete snapshot. Returns True when the visible state changed."""
        last_error = None
        for attempt in range(retries):
            try:
                snapshot = read_snapshot(self.state_dir)
            except (OSError, RuntimeError, ValueError, tomllib.TOMLDecodeError) as exc:
                last_error = exc
                if attempt + 1 < retries:
                    time.sleep(0.12 * (attempt + 1))
                continue
            with self.lock:
                if self.snapshot and self.snapshot.theme_version == snapshot.theme_version:
                    self.snapshot = replace(snapshot, stale=False)
                    return False
                self.snapshot = snapshot
                self.generation += 1
                return True
        if last_error:
            with self.lock:
                if self.snapshot is not None:
                    self.snapshot = replace(self.snapshot, stale=True)
            print(f"theme bridge: snapshot unavailable: {last_error}", file=sys.stderr)
        return False


class Broadcaster:
    def __init__(self):
        self.lock = threading.Lock()
        self.clients: set[queue.Queue] = set()

    def subscribe(self) -> queue.Queue:
        q: queue.Queue = queue.Queue(maxsize=1)
        with self.lock:
            self.clients.add(q)
        return q

    def unsubscribe(self, q: queue.Queue) -> None:
        with self.lock:
            self.clients.discard(q)

    def publish(self, snapshot: Snapshot) -> None:
        with self.lock:
            clients = list(self.clients)
        for q in clients:
            try:
                q.put_nowait(snapshot)
            except queue.Full:
                pass


class StateWatcher(threading.Thread):
    """inotify watcher; restart after each quiet change to re-arm directory watches."""

    def __init__(self, state: ThemeState, broadcaster: Broadcaster, stop: threading.Event):
        super().__init__(name="c2-theme-watcher", daemon=True)
        self.state = state
        self.broadcaster = broadcaster
        self.stop = stop

    def _publish_refresh(self) -> None:
        if self.state.refresh():
            snapshot = self.state.current()
            if snapshot:
                self.broadcaster.publish(snapshot)

    def run(self) -> None:
        if not shutil.which("inotifywait"):
            self._poll_fallback()
            return
        while not self.stop.is_set():
            proc = subprocess.Popen(
                ["inotifywait", "-m", "-r", "-e", "close_write,create,delete,move,attrib",
                 "--format", "%w%f", str(self.state.state_dir)],
                stdout=subprocess.PIPE, stderr=subprocess.DEVNULL, text=True, bufsize=1,
            )
            changed = False
            last_event = 0.0
            try:
                while not self.stop.is_set() and proc.poll() is None:
                    ready, _, _ = select.select([proc.stdout], [], [], 0.5)
                    if ready:
                        line = proc.stdout.readline()
                        if not line:
                            break
                        changed = True
                        last_event = time.monotonic()
                    elif changed and time.monotonic() - last_event >= 0.25:
                        break
                if changed:
                    time.sleep(0.08)
                    self._publish_refresh()
            finally:
                if proc.poll() is None:
                    proc.terminate()
                try:
                    proc.wait(timeout=2)
                except subprocess.TimeoutExpired:
                    proc.kill()
                    proc.wait(timeout=2)
                if proc.stdout:
                    proc.stdout.close()
            if proc.returncode not in (0, -15) and not self.stop.is_set():
                time.sleep(0.5)

    def _poll_fallback(self) -> None:
        # Only used if inotifywait is unavailable. Still cheap: three stat calls.
        while not self.stop.wait(5):
            self._publish_refresh()


def render_wallpaper(snapshot: Snapshot, max_width: int) -> tuple[bytes, str]:
    try:
        with Image.open(snapshot.wallpaper_path) as source:
            image = ImageOps.exif_transpose(source)
            if image.mode in ("RGBA", "LA") or "transparency" in image.info:
                rgba = image.convert("RGBA")
                canvas = Image.new("RGB", rgba.size, snapshot.background)
                canvas.paste(rgba, mask=rgba.getchannel("A"))
                image = canvas
            else:
                image = image.convert("RGB")
            if image.width > max_width:
                image.thumbnail((max_width, max_width), Image.Resampling.LANCZOS)
            out = io.BytesIO()
            image.save(out, "JPEG", quality=82, optimize=True, progressive=True)
            return out.getvalue(), "image/jpeg"
    except (OSError, ValueError):
        # A valid but oddly encoded wallpaper is better served than blank.
        data = snapshot.wallpaper_path.read_bytes()
        return data, image_mime(data[:16])


class BridgeServer(ThreadingHTTPServer):
    daemon_threads = True
    allow_reuse_address = True

    def __init__(self, address, handler, state: ThemeState, broadcaster: Broadcaster,
                 token: str, max_width: int):
        self.state = state
        self.broadcaster = broadcaster
        self.token = token
        self.max_width = max_width
        self.cache_lock = threading.Lock()
        self.cache: tuple[str, bytes, str] | None = None
        super().__init__(address, handler)


class Handler(BaseHTTPRequestHandler):
    protocol_version = "HTTP/1.1"
    server: BridgeServer

    def log_message(self, *_args):
        pass

    def _cors(self):
        self.send_header("Access-Control-Allow-Origin", "*")
        self.send_header("Access-Control-Allow-Methods", "GET, OPTIONS")
        self.send_header("Access-Control-Allow-Headers", "Authorization")

    def _authorized(self) -> bool:
        token = urllib.parse.parse_qs(urllib.parse.urlsplit(self.path).query).get("token", [None])[0]
        if token is None:
            auth = self.headers.get("Authorization", "")
            if auth.startswith("Bearer "):
                token = auth[7:]
        return bool(token) and hmac.compare_digest(str(token), self.server.token)

    def _json(self, status: int, body: dict):
        data = json.dumps(body, separators=(",", ":")).encode()
        self.send_response(status)
        self.send_header("Content-Type", "application/json; charset=utf-8")
        self.send_header("Content-Length", str(len(data)))
        self.send_header("Cache-Control", "no-store")
        self._cors()
        self.end_headers()
        self.wfile.write(data)

    def do_OPTIONS(self):
        self.send_response(204)
        self._cors()
        self.send_header("Content-Length", "0")
        self.end_headers()

    def do_GET(self):
        if not self._authorized():
            self._json(401, {"error": "token required"})
            return
        path = urllib.parse.urlsplit(self.path).path
        if path == "/events":
            self._events()
        elif path == "/api/theme":
            snapshot = self.server.state.current()
            if snapshot is None:
                self._json(503, {"error": "theme unavailable"})
                return
            self._json(200, snapshot.payload())
        elif path == "/api/wallpaper":
            self._wallpaper()
        elif path == "/health":
            snapshot = self.server.state.current()
            self._json(200, {"ok": True, "version": snapshot.theme_version if snapshot else None})
        else:
            self._json(404, {"error": "not found"})

    def _events(self):
        self.send_response(200)
        self.send_header("Content-Type", "text/event-stream; charset=utf-8")
        self.send_header("Cache-Control", "no-store")
        self.send_header("X-Accel-Buffering", "no")
        self.send_header("Connection", "close")
        self._cors()
        self.end_headers()
        q = self.server.broadcaster.subscribe()
        try:
            snapshot = self.server.state.current()
            if snapshot is not None:
                self._event(snapshot)
            self.wfile.write(b"retry: 2000\n\n")
            self.wfile.flush()
            while True:
                try:
                    snapshot = q.get(timeout=20)
                except queue.Empty:
                    self.wfile.write(b": heartbeat\n\n")
                    self.wfile.flush()
                else:
                    self._event(snapshot)
        except (BrokenPipeError, ConnectionResetError, OSError):
            pass
        finally:
            self.server.broadcaster.unsubscribe(q)

    def _event(self, snapshot: Snapshot):
        data = json.dumps(snapshot.payload(), separators=(",", ":")).encode()
        self.wfile.write(b"event: theme\nid: " + snapshot.theme_version.encode()
                         + b"\ndata: " + data + b"\n\n")
        self.wfile.flush()

    def _wallpaper(self):
        snapshot = self.server.state.current()
        if snapshot is None:
            self._json(503, {"error": "theme unavailable"})
            return
        etag = '"' + snapshot.wallpaper_version + '"'
        if self.headers.get("If-None-Match") == etag:
            self.send_response(304)
            self.send_header("ETag", etag)
            self.send_header("Cache-Control", "public, max-age=86400, immutable")
            self._cors()
            self.end_headers()
            return
        with self.server.cache_lock:
            cached = self.server.cache
            if cached is None or cached[0] != snapshot.wallpaper_version:
                data, mime = render_wallpaper(snapshot, self.server.max_width)
                self.server.cache = (snapshot.wallpaper_version, data, mime)
                cached = self.server.cache
        version, data, mime = cached
        self.send_response(200)
        self.send_header("Content-Type", mime)
        self.send_header("Content-Length", str(len(data)))
        self.send_header("ETag", '"' + version + '"')
        self.send_header("Cache-Control", "public, max-age=86400, immutable")
        self._cors()
        self.end_headers()
        self.wfile.write(data)


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(description="C2 Home theme bridge")
    parser.add_argument("--state-dir", type=Path,
                        default=Path.home() / ".local/state/omarchy/current")
    parser.add_argument("--bind", default="0.0.0.0")
    parser.add_argument("--port", type=int, default=8790)
    parser.add_argument("--token-file", type=Path,
                        default=Path.home() / ".config/c2-theme-bridge/token")
    parser.add_argument("--max-width", type=int, default=2560)
    args = parser.parse_args(argv)
    try:
        token = args.token_file.read_text().strip()
    except OSError as exc:
        print(f"theme bridge: cannot read token: {exc}", file=sys.stderr)
        return 2
    if not token:
        print("theme bridge: empty token", file=sys.stderr)
        return 2
    state = ThemeState(args.state_dir)
    state.refresh()
    broadcaster = Broadcaster()
    server = BridgeServer((args.bind, args.port), Handler, state, broadcaster,
                          token, args.max_width)
    stop = threading.Event()
    watcher = StateWatcher(state, broadcaster, stop)
    watcher.start()

    def shutdown(_signum, _frame):
        stop.set()
        threading.Thread(target=server.shutdown, daemon=True).start()

    signal.signal(signal.SIGTERM, shutdown)
    signal.signal(signal.SIGINT, shutdown)
    print(f"theme bridge on http://{args.bind}:{server.server_port}/", flush=True)
    try:
        server.serve_forever(poll_interval=0.5)
    finally:
        stop.set()
        server.server_close()
        watcher.join(timeout=3)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
